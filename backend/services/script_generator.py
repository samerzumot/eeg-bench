"""Reproducible script generator — creates a standalone .py file that reproduces the benchmark."""


def generate_script(dataset_name: str, results: dict) -> str:
    """Generate a complete, standalone Python script that reproduces the benchmark results."""
    versions = results.get("library_versions", {})
    pip_line = " ".join(f"{k}=={v}" for k, v in versions.items())

    return f'''#!/usr/bin/env python3
"""
EEG-Bench Reproducible Benchmark Script
=======================================
Dataset: {dataset_name}
Paradigm: 2-class Motor Imagery

Generated by EEG-Bench (https://eeg-bench.dev)

Requirements:
    pip install {pip_line} braindecode torch

References:
    - MOABB: Jayaram, V., & Barachant, A. (2018). MOABB: trustworthy algorithm
      benchmarking for BCIs. Journal of Neural Engineering, 15(6), 066011.
    - MNE-Python: Gramfort, A., et al. (2013). MEG and EEG data analysis with
      MNE-Python. Frontiers in Neuroscience, 7, 267.
    - Braindecode: Schirrmeister, R. T., et al. (2017). Deep learning with
      convolutional neural networks for EEG decoding and visualization.
      Human Brain Mapping, 38(11), 5391-5420.
    - pyRiemann: Barachant, A., et al. (2013). Classification of covariance
      matrices using a Riemannian-based kernel for BCI applications.
      Neurocomputing, 112, 172-178.
"""

from pyriemann.classification import MDM
from pyriemann.estimation import Covariances
from mne.decoding import CSP
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis as LDA
from sklearn.pipeline import Pipeline
from moabb.datasets import {dataset_name}
from moabb.evaluations import WithinSessionEvaluation
from moabb.paradigms import MotorImagery

# ── Dataset & Paradigm ──────────────────────────────────────────────
dataset = {dataset_name}()
paradigm = MotorImagery(n_classes=2, fmin=8, fmax=30)

# ── Pipelines ───────────────────────────────────────────────────────
pipelines = {{}}

# Pipeline 1: Common Spatial Patterns + Linear Discriminant Analysis
pipelines["CSP+LDA"] = Pipeline([
    ("CSP", CSP(n_components=8)),
    ("LDA", LDA()),
])

# Pipeline 2: Riemannian Minimum Distance to Mean
pipelines["Riemannian MDM"] = Pipeline([
    ("Covariances", Covariances(estimator="oas")),
    ("MDM", MDM(metric={{"mean": "riemann", "distance": "riemann"}})),
])

# ── Evaluation ──────────────────────────────────────────────────────
# Uses MOABB\'s WithinSessionEvaluation — handles subject-level cross-validation
evaluation = WithinSessionEvaluation(
    paradigm=paradigm,
    datasets=[dataset],
    overwrite=True,
)

results = evaluation.process(pipelines)

# ── Results ─────────────────────────────────────────────────────────
print("\\n" + "=" * 60)
print("EEG-Bench Benchmark Results")
print("=" * 60)
print(f"Dataset: {dataset_name}")
print(f"Paradigm: 2-class Motor Imagery (8-30 Hz)")
print()

summary = results.groupby("pipeline")[["score"]].agg(["mean", "std", "count"])
print(summary)

print("\\n── Per-Subject Breakdown ──")
for pipeline_name in pipelines:
    pdf = results[results["pipeline"] == pipeline_name]
    print(f"\\n{{pipeline_name}}:")
    for _, row in pdf.iterrows():
        print(f"  Subject {{int(row[\\'subject\\']):02d}}: {{row[\\'score\\'] * 100:.1f}}%")

print("\\n" + "=" * 60)
print("Library versions:")
import mne, moabb, pyriemann, sklearn
print(f"  mne={{mne.__version__}}, moabb={{moabb.__version__}}, "
      f"pyriemann={{pyriemann.__version__}}, scikit-learn={{sklearn.__version__}}")
'''
